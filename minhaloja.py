"""Funcionou! Mas... e se alguém passar uma lista vazia? E se passar valores negativos?

*Testar na mão não escala.* É aqui que entram as ferramentas do teste.


---

# 🔴 Fase 1 - Assertions: o guarda de segurança

A `assert` é como um **guarda na porta** do seu código.
Ela verifica uma condição e, se for falsa, **para tudo imediatamente** com uma mensagem de erro.

```
assert <condição>, "mensagem se falhar"
```

Use quando quiser **checar suposições críticas** durante o desenvolvimento.
"""

#=============================================
#FASE 1 - Assertions
#=============================================
def calcular_total(valores):
    # Guarda 1: a lista não pode ser None
    assert valores is not None, "❌ A lista de valores não pode ser None!"
    # Guarda 2: nenhum valor pode ser negativo
    assert all(v >= 0 for v in valores), "❌ Valores negativos não são permitidos!"
    return sum(valores)

# ✅ Caso válido - passa sem erro
print("Teste 1:", calcular_total([29.90, 15.00, 5.50]))

# ✅ Lista vazia - também válido (total - zero)
print("Teste 2:", calcular_total([]))

# ✅ Verificando resuldado esperado
assert calcular_total([10, 20, 30]) == 60, "Total errado!"
print("Teste 3: assert passou - resultado correto!")

# ❌ Provocando o erro - valor negativo na lista
# (descomente a linha abaixo para ver o AssertionError)


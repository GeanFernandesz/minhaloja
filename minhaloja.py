#===============================================================================

import unittest

def calcular_total(valores):
    return sum(valores)

class TestCaclularTotal(unittest.TestCase):
    """Suíte de testes da função calcular_total - PayPython."""

    def test_compra_normal(self):
        """Soma de valores positivos comuns."""

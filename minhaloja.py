##Vamos exercitar - classe Veiculo (classe pai)
class Veiculo:
  def __init__(self, marca, modelo, ano):
    self.marca = marca
    self.modelo = modelo
    self.ano = ano
    self.velocidade = 0     ##todo veiculo começa parado

  def acelerar(self, incremento):
    self.velocidade += incremento

  def frear(self, decremento):
    self.velocidade -= decremento

  def status(self):
    return (f"Marca: {self.marca}, Modelo: {self.modelo},"
            f"Ano: {self.ano}, Velocidade: {self.velocidade} km/h")

##Classes filhas - Carro e Bicicleta
class Carro(Veiculo):
  def __init__(self, marca, modelo, ano, potencia):
    super().__init__(marca, modelo, ano)     ##super() chama o construtor da classe pai
    self.potencia = potencia

##sobrescrevendo o método acelerar
  def acelerar(self, incremento):
    self.velocidade += incremento + self.potencia

class Bicicleta(Veiculo):
  def __init__(self, marca, modelo, ano,tipo):
    super().__init__(marca, modelo, ano)
    self.tipo = tipo

##Sobrescrevendo o status para incluir o tipo
  def status(self):
    return (f"Marca: {self.marca}, Modelo: {self.modelo}, "
            f"Ano: {self.ano}, Tipo: {self.tipo}, "
            f"Velocidade: {self.velocidade} km/h")

##Testando os objetos

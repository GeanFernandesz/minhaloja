"""💡 Quando usar Assertions?
| ✅ Use | ❌ Não use |
| :--- | :--- |
| Checar suposições internas do código | Validar dados de usuário em produção |
| Detectar bugs durante desenvolvimento | Substituir tratamento de exceções (`try/except`) |
| Verificar resultados intermediários | Lógica crítica de negócio |

>  ⚠️ Assertions podem ser desativadas em produção com ```python -0```. Para validação de negócio, use ```raise``` ou ```try/except```.


---

🟠 Fase 2 - Doctest: o teste que vive na documentação
Seu colega de equipe olha o código e pergunta:


> "Mas como eu sei como usar essa função?"

Com **doctest**, você escreve os exemplos de uso **dentro da documentação** da função.
E esses exemplos **viram testes automáticos**. Dois em um! ✅


"""

#====================================================================
# FASE 2 - Doctest
#====================================================================

def calcular_total(valores):
    """
    Calcula o total de uma lista de valores de compra.

    Parâmetros:
        valores (list): lista de números (float ou int)

    Retorna:
        float: soma dos valores

    Exemplos:
    >>> calcular_total([10, 20, 30])
    60
    >>> calcular_total([29.90, 15.00, 5.50])
    50.4
    >>> calcular_total([])
    0
    """
    return sum(valores)

#Rodando os doctests - compara a saída real com os exemplos acima
